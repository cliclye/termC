// Aliases live in one JSON file and are rendered to per-shell files that the
// shell integration re-sources whenever their mtime changes (hot reload).
const fs = require('node:fs');
const path = require('node:path');
const { TERMC_HOME, readJSON, writeJSON } = require('./util');

const FILE = path.join(TERMC_HOME, 'aliases.json');
const NAME_RE = /^[A-Za-z0-9_][A-Za-z0-9_.:-]*$/;

const DEFAULT_ALIASES = [
  { name: 'gs', command: 'git status' },
  { name: 'gp', command: 'git push' },
  { name: 'gl', command: 'git log --oneline --graph -20' },
  { name: 'dev', command: 'npm run dev' },
];

const sq = (s) => `'${String(s).replace(/'/g, `'\\''`)}'`;

function list() {
  const data = readJSON(FILE, null);
  if (!Array.isArray(data)) {
    writeJSON(FILE, DEFAULT_ALIASES);
    render(DEFAULT_ALIASES);
    return DEFAULT_ALIASES;
  }
  return data;
}

function render(aliases) {
  const valid = aliases.filter((a) => NAME_RE.test(a.name) && a.command);
  const names = valid.map((a) => a.name).join(' ');
  // Shells compare whole-second mtimes, so make sure every write moves it forward.
  const write = (file, text) => {
    const p = path.join(TERMC_HOME, file);
    let prev = 0;
    try {
      prev = Math.floor(fs.statSync(p).mtimeMs / 1000);
    } catch {}
    fs.writeFileSync(p, text);
    const now = Math.floor(Date.now() / 1000);
    const t = Math.max(now, prev + 1);
    fs.utimesSync(p, t, t);
  };
  const posix = (clear) =>
    [
      '# Generated by TermC. Edit aliases in TermC Settings.',
      `_termc_clear_aliases() { ${valid.length ? `${clear} ${names} 2>/dev/null` : ':'}; }`,
      ...valid.map((a) => `alias ${a.name}=${sq(a.command)}`),
      '',
    ].join('\n');
  write('aliases.zsh', posix('unalias'));
  write('aliases.bash', posix('unalias'));
  write(
    'aliases.fish',
    [
      '# Generated by TermC.',
      'function _termc_clear_aliases',
      ...valid.map((a) => `    functions -e ${a.name}`),
      'end',
      ...valid.map((a) => `alias ${a.name} ${sq(a.command)}`),
      '',
    ].join('\n'),
  );
}

function save(aliases) {
  const clean = [];
  const seen = new Set();
  for (const a of aliases) {
    const name = String(a.name || '').trim();
    const command = String(a.command || '').trim();
    if (!name || !command || seen.has(name)) continue;
    if (!NAME_RE.test(name)) throw new Error(`Invalid alias name "${name}"`);
    seen.add(name);
    clean.push({ name, command });
  }
  writeJSON(FILE, clean);
  render(clean);
  return clean;
}

function set(name, command) {
  const all = list().filter((a) => a.name !== name);
  all.push({ name, command });
  return save(all);
}

function remove(name) {
  return save(list().filter((a) => a.name !== name));
}

function ensure() {
  render(list());
}

module.exports = { list, save, set, remove, ensure };
